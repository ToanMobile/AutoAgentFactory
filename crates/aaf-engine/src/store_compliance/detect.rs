//! One bounded walk of the repository that collects every file the platform
//! scanners look at, plus the platform detection built on that inventory.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use super::kmp;
use super::text::{read_text, rel_str};

/// Deep enough for `ios/App/Sources/Feature/...`, shallow enough to stay bounded.
const MAX_DEPTH: usize = 20;
const MAX_ENTRIES: usize = 400_000;

/// Build output and vendored dependencies (docs/PLAN.md C.6): never app source.
const EXCLUDED_DIRS: [&str; 7] = [
    "build",
    ".gradle",
    "node_modules",
    "Pods",
    "Carthage",
    ".build",
    "DerivedData",
];

/// Test data is never shipped to a store.
const FIXTURE_DIRS: [&str; 3] = ["fixtures", "__fixtures__", "testdata"];

/// Compiled Apple products: their `Info.plist` is an output, not a source.
const BUNDLE_SUFFIXES: [&str; 6] = [
    ".app",
    ".appex",
    ".framework",
    ".xcframework",
    ".xcarchive",
    ".bundle",
];

/// JVM sources and resources of a Gradle source set (`src/main/java/...`):
/// deep package trees that hold none of the files the scanner reads.
const SOURCE_SET_DIRS: [&str; 3] = ["java", "kotlin", "res"];

/// Generated by the Unity editor next to `Assets/` and `ProjectSettings/`.
const UNITY_GENERATED: [&str; 4] = ["Library", "Temp", "Logs", "obj"];

/// All paths are relative to the scanned root.
#[derive(Default)]
pub(crate) struct Inventory {
    pub manifests: Vec<PathBuf>,
    pub gradle_files: Vec<PathBuf>,
    /// Kotlin/Groovy sources of `buildSrc` and `build-logic` convention plugins.
    pub convention_sources: Vec<PathBuf>,
    pub info_plists: Vec<PathBuf>,
    pub pbxprojs: Vec<PathBuf>,
    pub privacy_manifests: Vec<PathBuf>,
    pub infoplist_strings: Vec<PathBuf>,
    pub apple_sources: Vec<PathBuf>,
    /// Kotlin Multiplatform sources compiled for iOS (`src/iosMain/**/*.kt`).
    pub kotlin_apple_sources: Vec<PathBuf>,
    pub app_jsons: Vec<PathBuf>,
    pub app_configs: Vec<PathBuf>,
    pub pubspecs: Vec<PathBuf>,
    pub package_jsons: Vec<PathBuf>,
    pub unity_settings: Vec<PathBuf>,
    /// Directories that could not be listed, or the walk limit that was hit.
    pub problems: Vec<(String, String)>,
}

fn is_excluded_dir(name: &str, parent_is_unity: bool) -> bool {
    name.starts_with('.')
        || EXCLUDED_DIRS.contains(&name)
        || FIXTURE_DIRS.contains(&name)
        || BUNDLE_SUFFIXES.iter().any(|s| name.ends_with(s))
        || (parent_is_unity && UNITY_GENERATED.contains(&name))
}

fn is_cargo_target_dir(dir: &Path) -> bool {
    fs::symlink_metadata(dir.join("CACHEDIR.TAG"))
        .is_ok_and(|meta| meta.is_file() && !meta.file_type().is_symlink())
}

pub(crate) fn walk(root: &Path) -> Inventory {
    let mut inv = Inventory::default();
    let mut stack: Vec<(PathBuf, usize)> = vec![(PathBuf::new(), 0)];
    let mut seen = 0usize;
    // Directories cut by the depth bound: reported once, with the first one.
    let mut too_deep: Vec<String> = Vec::new();
    while let Some((rel, depth)) = stack.pop() {
        let dir = root.join(&rel);
        let entries = match fs::read_dir(&dir) {
            Ok(it) => it,
            Err(e) => {
                inv.problems.push((rel_str(&rel), e.to_string()));
                continue;
            }
        };
        // `DirEntry::file_type` does not follow symlinks, so a link is neither
        // a file nor a directory here and is skipped.
        let mut files = Vec::new();
        let mut dirs = Vec::new();
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            match entry.file_type() {
                Ok(t) if t.is_dir() => dirs.push(name),
                Ok(t) if t.is_file() => files.push(name),
                _ => {}
            }
        }
        files.sort();
        dirs.sort();
        seen += files.len() + dirs.len();
        if seen > MAX_ENTRIES {
            inv.problems.push((
                rel_str(&rel),
                format!("walk stopped after {MAX_ENTRIES} entries; the rest was not scanned"),
            ));
            break;
        }
        // Convention plugins keep the build logic we read in `src/main/kotlin`.
        let in_source_set = !in_convention_build(&rel)
            && rel
                .parent()
                .is_some_and(|p| p.file_name().is_some_and(|n| n == "src"));
        let is_unity =
            dirs.iter().any(|d| d == "Assets") && dirs.iter().any(|d| d == "ProjectSettings");
        for name in &files {
            classify(&mut inv, &rel, name);
        }
        for name in dirs.iter().rev() {
            if is_excluded_dir(name, is_unity) {
                continue;
            }
            if name == "target" && is_cargo_target_dir(&dir.join(name)) {
                continue;
            }
            // The Kotlin of an Apple source set is app code that reaches the
            // Apple SDK; every other source set stays unread.
            let apple_kotlin = name == "kotlin"
                && rel
                    .file_name()
                    .is_some_and(|set| kmp::is_apple_source_set(&set.to_string_lossy()));
            if in_source_set && SOURCE_SET_DIRS.contains(&name.as_str()) && !apple_kotlin {
                continue;
            }
            if depth + 1 > MAX_DEPTH {
                too_deep.push(rel_str(&rel.join(name)));
                continue;
            }
            stack.push((rel.join(name), depth + 1));
        }
    }
    too_deep.sort();
    if let Some(first) = too_deep.first() {
        inv.problems.push((
            first.clone(),
            format!(
                "{} directories deeper than {MAX_DEPTH} levels were not scanned (this is the first)",
                too_deep.len()
            ),
        ));
    }
    inv
}

/// Inside a `buildSrc` or `build-logic` included build.
fn in_convention_build(dir: &Path) -> bool {
    dir.components().any(|c| {
        let c = c.as_os_str();
        c == "buildSrc" || c == "build-logic"
    })
}

fn classify(inv: &mut Inventory, dir: &Path, name: &str) {
    let path = dir.join(name);
    let in_convention = in_convention_build(dir);
    let ext = name.rsplit_once('.').map(|(_, e)| e).unwrap_or("");
    if in_convention && matches!(ext, "kt" | "kts" | "gradle" | "groovy" | "java") {
        inv.convention_sources.push(path);
        return;
    }
    match name {
        "AndroidManifest.xml" => inv.manifests.push(path),
        "build.gradle" | "build.gradle.kts" => inv.gradle_files.push(path),
        "Info.plist" => inv.info_plists.push(path),
        "project.pbxproj" => inv.pbxprojs.push(path),
        "PrivacyInfo.xcprivacy" => inv.privacy_manifests.push(path),
        "InfoPlist.strings" | "InfoPlist.xcstrings" => inv.infoplist_strings.push(path),
        "app.json" => inv.app_jsons.push(path),
        "app.config.js" | "app.config.ts" | "app.config.mjs" | "app.config.cjs" => {
            inv.app_configs.push(path);
        }
        "pubspec.yaml" => inv.pubspecs.push(path),
        "package.json" => inv.package_jsons.push(path),
        "ProjectSettings.asset" if dir.ends_with("ProjectSettings") => {
            inv.unity_settings.push(path);
        }
        _ if matches!(ext, "swift" | "m" | "mm") => inv.apple_sources.push(path),
        _ if ext == "kt" && kmp::in_apple_source_set(dir) => {
            inv.kotlin_apple_sources.push(path);
        }
        _ => {}
    }
}

/// Mobile platforms present in the inventory. An empty set means the repo is
/// not a mobile project.
pub(crate) fn platforms(root: &Path, inv: &Inventory) -> BTreeSet<&'static str> {
    let mut found = BTreeSet::new();
    if !inv.manifests.is_empty() {
        found.insert("android");
    }
    if !inv.pbxprojs.is_empty() {
        found.insert("ios");
    }
    if !inv.unity_settings.is_empty() {
        found.insert("unity");
    }
    let contains = |paths: &[PathBuf], needles: &[&str]| {
        paths.iter().any(|p| {
            // An unreadable marker file only means "not detected through it";
            // the files that matter are reported by the scanner that owns them.
            read_text(&root.join(p))
                .map(|t| needles.iter().any(|n| t.contains(n)))
                .unwrap_or(false)
        })
    };
    if contains(&inv.pubspecs, &["sdk: flutter"]) {
        found.insert("flutter");
    }
    if contains(&inv.package_jsons, &["\"react-native\""]) {
        found.insert("react-native");
    }
    if contains(&inv.package_jsons, &["\"expo\""]) || contains(&inv.app_jsons, &["\"expo\""]) {
        found.insert("expo");
    }
    found
}
