  function readStorage(key) {
    try {
      const store = typeof window !== "undefined" ? window.localStorage : (typeof localStorage !== "undefined" ? localStorage : null);
      return store ? store.getItem(key) : null;
    } catch (_) {
      return null;
    }
  }

  function writeStorage(key, val) {
    try {
      const store = typeof window !== "undefined" ? window.localStorage : (typeof localStorage !== "undefined" ? localStorage : null);
      if (store) store.setItem(key, val);
    } catch (_) {}
  }

  function normalizeLang(lang) {
    const raw = String(lang || "").trim().toLowerCase();
    return VALID_LANGS.has(raw) ? raw : "en";
  }

  let currentLang = normalizeLang(readStorage(LANG_KEY));

  function getLang() {
    return currentLang;
  }

  function t(key, params) {
    const lang = getLang();
    const table = DICT[lang] || DICT.en;
    let template = Object.prototype.hasOwnProperty.call(table, key)
      ? table[key]
      : (Object.prototype.hasOwnProperty.call(DICT.en, key) ? DICT.en[key] : String(key ?? ""));
    if (params && typeof params === "object") {
      template = template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => (
        Object.prototype.hasOwnProperty.call(params, name) ? String(params[name] ?? "") : match
      ));
    }
    return template;
  }

  function applyDom(root) {
    const scope = root || (typeof document !== "undefined" ? document : null);
    if (!scope || typeof scope.querySelectorAll !== "function") return;
    if (typeof document !== "undefined" && document.documentElement) {
      document.documentElement.lang = getLang();
    }
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.title = t(key);
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.placeholder = t(key);
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (key) el.setAttribute("aria-label", t(key));
    });
  }

  function notifyListeners(lang) {
    listeners.forEach((cb) => {
      try {
        cb(lang);
      } catch (_) {}
    });
  }

  function setLang(lang) {
    const next = normalizeLang(lang);
    currentLang = next;
    writeStorage(LANG_KEY, next);
    if (typeof document !== "undefined" && document.documentElement) {
      document.documentElement.lang = next;
    }
    applyDom(typeof document !== "undefined" ? document : null);
    notifyListeners(next);
    return next;
  }

  function onChange(cb) {
    if (typeof cb !== "function") return () => {};
    listeners.add(cb);
    return () => listeners.delete(cb);
  }

